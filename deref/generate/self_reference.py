"""Self-generated reference (LLMBar-style "reference" baseline, Table 2): the judge model itself first writes the
expected value from its own truncated (Plain) input, then judges the candidate with that output in its input.

Generation prompt (one per locator slot = state, Function line, Parameter line, parameter name; all candidates of a slot
share it), rendered with the judge model's own chat template, thinking off:
  system: SYSTEM (the LLMBar system prompt)
  user:   <Plain context without its "Proposed value for ..." line>
          "\\nGive the value of parameter <name> for this call."
Decoding: greedy (temperature 0), at most 384 new tokens, vLLM engine and request seed 20260930, max_model_len 8,192.

Judge input: the Plain state re-laddered with the 2,048-token rule of the DeRef inputs (`reference.insert_block`) +
"\\n" + HEAD + "\\n" + <generation, stripped> + the argument tail (Function / Parameter / Proposed value lines). Every
analysis argument gets one item `<argument item_id>|self_reference`: when the generation is empty, or the input is over
2,048 CLM tokens at every rung, the item carries the Plain context (it is scored again in the same run, as in the paper).
"""
import json
import time
from pathlib import Path

from deref.generate import render as R
from deref.inputs import reference as RF
from deref.inputs import state as ST
from deref.inputs.plain import base_parts

SYSTEM = "You are a helpful assistant that responds to the user in a concise way."
HEAD = "A reference output generated by a strong AI assistant:"
ASK = "\nGive the value of parameter {name} for this call."
TAG = "self_reference"
CAP, MAX_MODEL_LEN, SEED = 384, 8192, 20260930
# judge name (scoring) -> generation model name (deref.generate.models)
JUDGE_MODEL = {"qwen3_8b": "qwen3_8b", "qwen3_8_27b": "qwen3_8_27b"}
FORBIDDEN = ("Before seeing any proposed value", "where in the context does it come from", "at most 3 sentences")


def plain_without_value(rec, arg):
    """(Plain context without the `Proposed value for` line, parameter name)."""
    S, _, tail, _ = base_parts(rec, arg)
    ctx = S + tail
    assert ctx.count(ST.VALUE_LINE) == 1, arg["item_id"]
    body = ctx.rsplit(ST.VALUE_LINE, 1)[0]
    return body, arg["name"]


def user_text(rec, arg):
    body, name = plain_without_value(rec, arg)
    u = body + ASK.format(name=name)
    assert not any(t.lower() in u.lower() for t in FORBIDDEN), arg["item_id"]
    return u


def build_prompts(records, dataset, tok, judge, analysis_only=True):
    """(prompt rows, map rows) for one dataset and one judge model; prompts are shared by the candidates of a slot.
    Prompt rows {"prompt_id", "text", "tokens", "dataset"}; map rows {"item_id", "prompt_id"}."""
    items = sorted(ST.arguments(records, analysis_only), key=lambda x: x[1]["item_id"])
    rows, index, mp = [], {}, []
    for rec, arg in items:
        S, _, tail, _ = base_parts(rec, arg)
        _, fl, pl = R.split_main(S + tail)
        slot = (rec["state_id"], fl, pl, arg["name"])
        u = user_text(rec, arg)
        if slot not in index:
            text = R.chat(tok, u, SYSTEM)
            n = R.ntok(tok, text)
            assert n + CAP <= MAX_MODEL_LEN, arg["item_id"]
            index[slot] = (f"{TAG}_{judge}|{dataset}|{len(rows):05d}", u)
            rows.append({"prompt_id": index[slot][0], "text": text, "tokens": n, "dataset": dataset})
        else:
            assert index[slot][1] == u, f"candidates of one slot differ outside the value line: {arg['item_id']}"
        mp.append({"item_id": arg["item_id"], "prompt_id": index[slot][0]})
    return rows, mp


def generate(prompts_path, out_path, judge):
    """Greedy generation of the self-generated references (GPU, vLLM). Output rows {"prompt_id", "output", "new_tokens",
    "prompt_tokens", "finish_reason", "empty"}."""
    from transformers import AutoTokenizer
    from vllm import LLM, SamplingParams
    from vllm.inputs import TokensPrompt

    from deref.generate.models import MODELS
    m = MODELS[JUDGE_MODEL[judge]]
    tok = AutoTokenizer.from_pretrained(m["repo_id"], revision=m["revision"])
    with open(prompts_path, encoding="utf-8") as f:
        prompts = [json.loads(line) for line in f if line.strip()]
    ids = [tok(p["text"], add_special_tokens=False)["input_ids"] for p in prompts]
    for p, x in zip(prompts, ids):
        assert len(x) == p["tokens"] and len(x) + CAP <= MAX_MODEL_LEN, p["prompt_id"]
    print(f"[self-reference] {judge}: {len(prompts)} prompts, max {max(map(len, ids))} tokens")
    llm = LLM(model=m["repo_id"], revision=m["revision"], dtype="bfloat16", max_model_len=MAX_MODEL_LEN,
              gpu_memory_utilization=0.9, limit_mm_per_prompt={"image": 0, "video": 0}, seed=SEED)
    sp = SamplingParams(temperature=0.0, max_tokens=CAP, seed=SEED, skip_special_tokens=True)
    t0 = time.time()
    res = llm.generate([TokensPrompt(prompt_token_ids=x) for x in ids], sp)
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    capped = empty = 0
    with open(out_path, "w", encoding="utf-8") as f:
        for p, x, r in zip(prompts, ids, res):
            o = r.outputs[0]
            capped += o.finish_reason == "length"
            empty += not o.text.strip()
            f.write(json.dumps({"prompt_id": p["prompt_id"], "output": o.text, "new_tokens": len(o.token_ids),
                                "prompt_tokens": len(x), "finish_reason": o.finish_reason,
                                "empty": not o.text.strip()}, ensure_ascii=False) + "\n")
    print(f"[done] {len(prompts)} prompts in {time.time() - t0:.0f} s; hit the {CAP}-token cap: {capped}; empty: {empty}")


def build_items(records, generations, item_map, tok, analysis_only=True):
    """(rows, stats): one judge item per mapped argument (see the module docstring); tok = Qwen3-8B (CLM length)."""
    rows, stats = [], {"items": 0, "extra truncation": 0, "Plain kept (empty generation)": 0,
                       "Plain kept (over 2,048 at every rung)": 0}
    for rec, arg in ST.arguments(records, analysis_only):
        pid = item_map.get(arg["item_id"])
        if pid is None:
            continue
        stats["items"] += 1
        ref = generations[pid].strip()
        r = None
        if ref:
            r = RF.insert_block(rec, arg, "\n" + HEAD + "\n" + ref, tok, TAG)
            if r is None:
                stats["Plain kept (over 2,048 at every rung)"] += 1
        else:
            stats["Plain kept (empty generation)"] += 1
        if r is None:
            S, lab, tail, q = base_parts(rec, arg)
            r = {"item_id": f"{arg['item_id']}|{TAG}", "base_item": arg["item_id"], "context": S + tail, "question": q,
                 "clm_tokens": None, "truncation": lab, "extra_truncation": False, "plain_kept": True}
        stats["extra truncation"] += bool(r["extra_truncation"])
        rows.append(r)
    return rows, stats
