"""Build the judge inputs of the self-generated reference baseline (Table 2) for one judge.

Each analysis argument gets the item `<argument item_id>|self_reference`: the Plain state (re-laddered to <= 2,048
Qwen3-8B tokens with the rule of the DeRef inputs) + "\\nA reference output generated by a strong AI assistant:\\n" +
the judge's own generation (stripped) + the argument tail. Empty generations and inputs over the limit at every rung
keep the Plain context under the same item id (they are scored again together with the other items).
Reads <data-dir>/data/<dataset>.jsonl, <gen-dir>/generations/self_reference_<judge>.jsonl,
<gen-dir>/prompts/self_reference_<judge>_map.jsonl and the Qwen3-8B tokenizer. Writes
<out>/self_reference_<judge>_<dataset>.jsonl (rows {"item_id", "base_item", "context", "question", ...}).
Score them with 42_score_local_judge.py (same judge) into <scores_dir>/<dataset>/self_reference/<judge>.jsonl.

  python scripts/82_build_self_reference_items.py --judge qwen3_8b --data-dir <deref_data> --gen-dir <gen_dir> --out <inputs_dir>
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from deref.common import write_jsonl  # noqa: E402
from deref.generate import self_reference as SR  # noqa: E402
from deref.inputs import reference as RF  # noqa: E402
from deref.inputs import state as ST  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--judge", required=True, choices=sorted(SR.JUDGE_MODEL))
    ap.add_argument("--data-dir", required=True, help="data package directory")
    ap.add_argument("--gen-dir", required=True, help="directory with generations/ and prompts/")
    ap.add_argument("--out", required=True, help="output directory")
    ap.add_argument("--datasets", nargs="+", default=list(ST.DATASETS), choices=ST.DATASETS)
    ap.add_argument("--tokenizer-qwen3-8b", default=None, help="local tokenizer directory (default: Hugging Face id)")
    a = ap.parse_args()
    name = f"{SR.TAG}_{a.judge}"
    gens = RF.load_generations(Path(a.gen_dir) / "generations" / f"{name}.jsonl")
    mp = RF.load_map(Path(a.gen_dir) / "prompts" / f"{name}_map.jsonl")
    tok = ST.load_tokenizer(ST.QWEN3_8B, a.tokenizer_qwen3_8b)
    for d in a.datasets:
        rows, stats = SR.build_items(ST.load_records(a.data_dir, d), gens, mp, tok)
        write_jsonl(Path(a.out) / f"{name}_{d}.jsonl", rows)
        print(f"[self-reference] {a.judge} {d}: {json.dumps(stats)}")


if __name__ == "__main__":
    main()
